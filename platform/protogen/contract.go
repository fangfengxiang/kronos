package main

import (
	"fmt"
	"go/token"
	"path"
	"slices"
	"strconv"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/gofeaturespb"
)

const contractFilename = "contract.kronos.pb.go"

type contract struct {
	aliases  []symbolAlias
	services []unaryService
	names    map[string]protogen.GoImportPath
	bindings bool
}

type symbolAlias struct {
	identifier  protogen.GoIdent
	declaration string
}

type unaryService struct {
	name           string
	descriptor     *protogen.Service
	fileDescriptor protogen.GoIdent
	methods        []*protogen.Method
}

func generateContract(plugin *protogen.Plugin, apiImport string, unaryBindings bool) error {
	packageName := path.Base(apiImport)
	if !strings.Contains(apiImport, "/") || strings.HasPrefix(apiImport, "/") || strings.HasPrefix(apiImport, "../") ||
		path.Clean(apiImport) != apiImport || strings.ContainsAny(apiImport, "\\\n\r\t ") ||
		packageName == "_" || packageName == "main" || !token.IsIdentifier(packageName) {
		return fmt.Errorf("invalid api_import %q", apiImport)
	}
	var inputs []*protogen.File
	for _, file := range plugin.Files {
		if file.Generate {
			inputs = append(inputs, file)
		}
	}
	if len(inputs) == 0 {
		return fmt.Errorf("no input Proto files for %s", apiImport)
	}
	slices.SortFunc(inputs, func(first, second *protogen.File) int {
		return strings.Compare(first.Desc.Path(), second.Desc.Path())
	})
	plan := contract{names: make(map[string]protogen.GoImportPath), bindings: unaryBindings}
	wireRoot := apiImport + "/internal/wire"
	for _, file := range inputs {
		wireImport := string(file.GoImportPath)
		if wireImport != wireRoot && !strings.HasPrefix(wireImport, wireRoot+"/") {
			return fmt.Errorf("%s: go_package %s must use %s", file.Desc.Path(), file.GoImportPath, wireRoot)
		}
		if file.Desc.Syntax() != protoreflect.Proto3 || file.APILevel != gofeaturespb.GoFeatures_API_OPEN {
			return fmt.Errorf("%s: Kronos requires the Proto3 Open Go API", file.Desc.Path())
		}
		if err := plan.collectFile(file); err != nil {
			return fmt.Errorf("%s: %w", file.Desc.Path(), err)
		}
	}
	for _, service := range plan.services {
		for _, method := range service.methods {
			for _, message := range []*protogen.Message{method.Input, method.Output} {
				identifier := message.GoIdent
				if strings.Contains(string(identifier.GoImportPath), "/internal/") && plan.names[identifier.GoName] != identifier.GoImportPath {
					return fmt.Errorf("%s: private type %s must be exported by the same contract", method.Desc.FullName(), message.Desc.FullName())
				}
			}
		}
	}

	output := plugin.NewGeneratedFile(path.Join(apiImport, contractFilename), protogen.GoImportPath(apiImport))
	output.P("// Code generated by protoc-gen-kronos. DO NOT EDIT.")
	output.P("package ", packageName)
	output.P()
	for _, alias := range plan.aliases {
		output.P(alias.declaration, " ", alias.identifier.GoName, " = ", output.QualifiedGoIdent(alias.identifier))
	}
	for _, service := range plan.services {
		output.P()
		output.P("// ", service.name, " implements the unary methods declared in Protobuf.")
		output.P("type ", service.name, " interface {")
		for _, method := range service.methods {
			ctx := output.QualifiedGoIdent(protogen.GoImportPath("context").Ident("Context"))
			input := plan.publicName(output, method.Input.GoIdent)
			response := plan.publicName(output, method.Output.GoIdent)
			output.P(method.GoName, "(", ctx, ", *", input, ") (*", response, ", error)")
		}
		output.P("}")
		if plan.bindings {
			plan.writeUnaryBinding(output, service)
		}
	}
	return nil
}

func (plan *contract) collectFile(file *protogen.File) error {
	for _, enum := range file.Enums {
		if err := plan.collectEnum(enum); err != nil {
			return err
		}
	}
	for _, message := range file.Messages {
		if err := plan.collectMessage(message); err != nil {
			return err
		}
	}
	for _, service := range file.Services {
		unary := unaryService{name: service.GoName + "UnaryService", descriptor: service, fileDescriptor: file.GoDescriptorIdent}
		for _, method := range service.Methods {
			if !method.Desc.IsStreamingClient() && !method.Desc.IsStreamingServer() {
				unary.methods = append(unary.methods, method)
			} else if plan.bindings {
				return fmt.Errorf("%s requires unary methods for Kronos bindings", method.Desc.FullName())
			}
		}
		if len(unary.methods) != 0 {
			if err := plan.reserveName(unary.name, ""); err != nil {
				return err
			}
			if plan.bindings {
				for _, name := range []string{service.GoName + "Name", "Bind" + service.GoName} {
					if err := plan.reserveName(name, ""); err != nil {
						return err
					}
				}
			}
			plan.services = append(plan.services, unary)
		}
	}
	return nil
}

func (plan *contract) writeUnaryBinding(output *protogen.GeneratedFile, service unaryService) {
	kronos := protogen.GoImportPath("github.com/fangfengxiang/kronos/platform/kronos")
	serviceName := service.descriptor.GoName
	output.P()
	output.P("// ", serviceName, "Name is the default discovery name.")
	output.P("const ", serviceName, "Name = ", strconv.Quote(string(service.descriptor.Desc.FullName())))
	output.P()
	output.P("// Bind", serviceName, " binds an implementation of the Protobuf service.")
	output.P("func Bind", serviceName, "(implementation ", service.name, ") ", output.QualifiedGoIdent(kronos.Ident("Service")), " {")
	output.P("descriptor := ", output.QualifiedGoIdent(service.fileDescriptor),
		".Services().ByName(", strconv.Quote(string(service.descriptor.Desc.Name())), ")")
	output.P("if implementation == nil {")
	output.P("return ", output.QualifiedGoIdent(kronos.Ident("Bind")), "(descriptor)")
	output.P("}")
	output.P("return ", output.QualifiedGoIdent(kronos.Ident("Bind")), "(descriptor,")
	for _, method := range service.methods {
		input := plan.publicName(output, method.Input.GoIdent)
		response := plan.publicName(output, method.Output.GoIdent)
		output.P(output.QualifiedGoIdent(kronos.Ident("Unary")), "(", strconv.Quote(string(method.Desc.Name())),
			", &", input, "{}, &", response, "{}, implementation.", method.GoName, "),")
	}
	output.P(")")
	output.P("}")
}

func (plan *contract) collectEnum(enum *protogen.Enum) error {
	if err := plan.addAlias(enum.GoIdent, "type"); err != nil {
		return err
	}
	for _, value := range enum.Values {
		if err := plan.addAlias(value.GoIdent, "const"); err != nil {
			return err
		}
	}
	return nil
}

func (plan *contract) collectMessage(message *protogen.Message) error {
	if message.Desc.IsMapEntry() {
		return nil
	}
	if message.APILevel != gofeaturespb.GoFeatures_API_OPEN {
		return fmt.Errorf("message %s requires the Open Go API", message.Desc.FullName())
	}
	if err := plan.addAlias(message.GoIdent, "type"); err != nil {
		return err
	}
	for _, oneof := range message.Oneofs {
		if oneof.Desc.IsSynthetic() {
			continue
		}
		for _, field := range oneof.Fields {
			if err := plan.addAlias(field.GoIdent, "type"); err != nil {
				return err
			}
		}
	}
	for _, enum := range message.Enums {
		if err := plan.collectEnum(enum); err != nil {
			return err
		}
	}
	for _, nested := range message.Messages {
		if err := plan.collectMessage(nested); err != nil {
			return err
		}
	}
	return nil
}

func (plan *contract) addAlias(identifier protogen.GoIdent, declaration string) error {
	if err := plan.reserveName(identifier.GoName, identifier.GoImportPath); err != nil {
		return err
	}
	plan.aliases = append(plan.aliases, symbolAlias{identifier: identifier, declaration: declaration})
	return nil
}

func (plan *contract) reserveName(name string, owner protogen.GoImportPath) error {
	if _, exists := plan.names[name]; exists {
		return fmt.Errorf("duplicate public Go declaration %s", name)
	}
	plan.names[name] = owner
	return nil
}

func (plan *contract) publicName(output *protogen.GeneratedFile, identifier protogen.GoIdent) string {
	if plan.names[identifier.GoName] == identifier.GoImportPath {
		return identifier.GoName
	}
	return output.QualifiedGoIdent(identifier)
}
